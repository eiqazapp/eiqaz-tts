# هياكل B المعتمدة (لرصد التعارض — Q تتقدم على B في وضع الفصحى فقط)
B_SKELETONS = {
    'rqm', 'rqmp', 'rqmnp', '>rqAm', 'trqym',
    'qr|n', 'qr|ny', 'qr|nyp', 'qrAn', 'qrAny',
    'mqAm', 'mqAmAt',
    'qAnwn', 'qAnwny', 'qAnwnyp', 'qwAnyn',
    'qr$', 'qrw$', 'qyrAT', 'qrAryT', 'qnTAr', 'qnATyr',
}

CAT_AR = {
    'math': 'رياضيات/حساب',
    'sci': 'علوم/جغرافيا',
    'civic': 'اجتماعيات/سجل فصيح',
    'lang': 'لغة/نحو',
}


def skel_of(word_ar):
    buck = arabic_to_buckwalter(word_ar).strip()
    s = ''.join(c for c in buck if c not in _QAF_DIAC)
    return buck, s


def main():
    out, seen, problems = [], {}, []
    for w, cat, why in WORDS:
        buck, s = skel_of(w)
        if not s or 'q' not in s:
            problems.append((w, buck, 'no q in skeleton'))
            continue
        if s in seen:
            # توثيق المرادف فقط؛ الهيكل يُدرج مرة
            out[-1]['also'] = out[-1].get('also', []) + [w] \
                if out and out[-1]['skel'] == s else out[-1].get('also', [])
            continue
        seen[s] = w
        entry = {
            'word_ar': w, 'buckwalter': buck, 'skel': s,
            'category': cat, 'category_ar': CAT_AR[cat],
            'rationale': why,
            'conflicts_with_B': s in B_SKELETONS,
        }
        out.append(entry)

    skels = sorted({e['skel'] for e in out})
    n_b_conflict = sum(1 for e in out if e['conflicts_with_B'])

    doc = {
        'meta': {
            'name': 'QAF_Q_SKELETONS (الفئة Q — سجل فصحى/تعليمي)',
            'version': 'q-v1.0',
            'date': '2026-10-01',
            'purpose': (
                'كلمات ببعينها (قائمة مغلقة) تُنطق بالقاف الأصيلة [q] في سياق '
                'التعليم والمصطلحات المنهجية والسجل الفصيح — لا تُطبَّق على كل '
                'كلمة تحتوي قافًا. تُفعَّل فقط في وضع «qaf» (فصحى المصطلحات) '
                'ولا تغيّر الوضع الافتراضي auto المعتمد إطلاقًا.'),
            'sources': [
                'أمثلة المستخدم الصريحة (رقم، أرقام، قسمة، يقسم، تقريب)',
                'مصطلحات مناهج مصر: رياضيات/علوم/لغة/اجتماعيات (قاعدة معرفية)',
                'qaf_audit_full.json: إحصاء corpus نيلتس — 31,294 موضع قاف '
                'وأعلى 60 هيكلًا كلها عامية بالهمزة؛ لا سجل فصحى في العامية',
                'البحث الويب مؤجل (حصة API مستنفدة 429) — قابل للتوسيع لاحقًا',
            ],
            'conflict_policy': (
                'الكلمات المشتركة مع B (رقم/أرقام/ترقيم/قانون عائلاته/مقام): '
                'في وضع auto تبقى على قرار B ([g]) دون تغيير (قرار معتمد '
                'ساري)؛ وفي وضع qaf (فصحى المصطلحات) تفوز Q بالقاف الفصحى. '
                'الوضعان منفصلان تمامًا.'),
            'sound_note': (
                'في النموذج الحالي (from-scratch، توكن q غير مدرَّب: 0/1.59M) '
                'تُقرَّب القاف الفصحى بأقرب صوت مدرَّب [k] (كاف ثقيلة). القاف '
                'الأصيلة الحقيقية uvular /q/ تتطلب إعادة تدريب — المشروع '
                'المؤجل المستقل.'),
            'n_words': len(out), 'n_skeletons': len(skels),
            'n_conflicts_with_B': n_b_conflict,
        },
        'entries': out,
        'skeletons': skels,
    }
    val_dir = os.path.join(REPO, 'validation')
    with open(os.path.join(val_dir, 'qaf_q_list.json'), 'w',
              encoding='utf-8') as f:
        json.dump(doc, f, ensure_ascii=False, indent=1)

    print(f'كلمات: {len(out)} | هياكل فريدة: {len(skels)} | '
          f'تعارض مع B: {n_b_conflict}')
    if problems:
        print('مشاكل:', problems)
    print()
    print('# literal جاهز للصق في infer.py:')
    parts = []
    for s in skels:
        if "'" in s:
            parts.append(f'"{s}"')      # هياكل فيها hamza (') → اقتباس مزدوج
        else:
            parts.append(f"'{s}'")
    print('QAF_Q_SKELETONS = frozenset({')
    for i in range(0, len(parts), 5):
        print('    ' + ', '.join(parts[i:i + 5]) + ',')
    print('})')
    print()
    print('تعارضات B:', sorted(e['skel'] for e in out
                               if e['conflicts_with_B']))


