"""det_extend_internal_vowels.py — توسعة common_map بالحركات الداخلية
المصرية المستخلصة من corpus التشكيل (أدلة تكرارية موثقة).

المصدر: مسح corpus التشكيل المصري المعتمد (21,880 نصًا؛ 306,987 كلمة —
work/ph3_full_output.jsonl = مخرجات محرك v5.3 على دليل التشكيل v2.1).
لكل مدخل: n = مواضع الكلمة في corpus، family = نسبة العائلة المهيمنة
(بعد توحيد السكون النهائي المرسوم — فرق تجميلي بلا أثر في النطق).

معيار القبول (موثق ولا يستخدم أي حدس لغوي جديد):
  1) الكلمة غير مغطاة بأي خريطة/قاعدة det قائمة.
  2) مخرج مسار الإنتاج الحالي (catt+det) يخالف العائلة المهيمنة في
     حركات داخلية فعلية (قياس scripts/compare_pipeline_vs_corpus.py).
  3) عائلة مهيمنة >= 47% من المواضع، وفي كل حالة شكل catt الحالي
     بلا أي سند يُذكر في corpus.
  4) ليست كلمة سياقية التباس (اعمل: أَعْمَل/اِعْمَل — مستبعدة؛
     بنروح/هنعمل: تصريفات ضعيفة الركن — مستبعدة).

المستبعدة عمدًا (توثيق الشفافية):
  عشان (عَشَان 39% مقابل عَشَّان/عِشَان — انقسام فعلي)
  يمكن (31%)، غير (44%)، بص (20%)، برضه (n=20 فقط)
  اعمل (سياقية: أَعْمَل «أفعل» 62% مقابل اِعْمَل «أمر» 27%)
  نفس الكلمة نفسها: مهيمنة 90% مع قراءة نَفَس نادرة (5%) — أُدرجت
  والالتباس موثق.

الحالة المرجعية: مؤقتة — الأشكال من معيار المشروع نفسه (corpus الذي
درّب النموذج عليه) لا من مراجعة لغوية بشرية جديدة. هذا امتداد لقاعدة
المشروع القائمة «القوائم المغلقة من أدلة corpus» (نهج قاموس القاف).

الاستخدام (إعادة تشغيل idempotent):
  python validation/det_extend_internal_vowels.py
يحدّث inference/lib/det_data/det_lists.json إلى det-v1.3.
"""
