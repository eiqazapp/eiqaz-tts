# (المفتاح المطوي، الشكل الهدف، n المواضع، عائلة%، ملاحظة)
# الشكل النهائي يتبع أسلوب الخريطة القائمة: سكون نهائي مرسوم على
# الحرف الساكن الأخير، والحروف الطويلة/ة تبقى عارية (§ج).
